 <h2 id="s3">3. Why Melasma Is Hard to Treat — Common Mistakes</h2>
 <p>Many clients come to DIVA Skin Clinic Poipet having tried treatments elsewhere that did not work — or that made their melasma worse. The most common reasons:</p>
 <ul>
 <li><strong>Wrong laser selection</strong> — using CO2 laser or intense IPL on melasma-prone skin can trigger post-inflammatory hyperpigmentation and make melasma worse.</li>
 <li><strong>Too aggressive too fast</strong> — doing multiple strong sessions without allowing proper recovery stimulates more melanin production.</li>
 <li><strong>Not using sunscreen</strong> — melasma is directly triggered by UV exposure. No treatment will hold without strict daily sunscreen use.</li>
 <li><strong>Using market whitening products</strong> — some contain steroids or mercury that cause a rebound effect when stopped.</li>
 <li><strong>Hormonal triggers not managed</strong> — melasma connected to oral contraceptives or hormonal changes requires additional management.</li>
 </ul>
 <p>At DIVA Skin Clinic Poipet, we explain these risks during consultation. Melasma treatment works best when approached patiently, with the right methods and consistent homecare.</p>

