 <h2 id="s4">4. Safety, Screening and Side Effects</h2>
 <p>Before starting any weight management program at DIVA Skin Clinic Poipet, the following information must be provided:</p>
 <ul>
 <li>Current weight and height (BMI calculation)</li>
 <li>Medical history — thyroid conditions, pancreatitis, kidney issues, cardiovascular history</li>
 <li>Full list of current medications and supplements</li>
 <li>Allergies to medications or injectable products</li>
 <li>Weight loss history — previous attempts and results</li>
 <li>Treatment goal and expected timeline</li>
 </ul>
 <h3>Common Side Effects</h3>
 <p>Side effects are common, especially when starting or increasing the dose at DIVA Skin Clinic Poipet:</p>
 <ul>
 <li>Nausea — most common, especially in the first few weeks</li>
 <li>Reduced appetite / early satiety</li>
 <li>Fatigue</li>
 <li>Vomiting or diarrhea in some clients</li>
 <li>Mild injection site reactions</li>
 </ul>
 <p>Most side effects reduce over time as the body adjusts. DIVA Skin Clinic Poipet provides guidance on how to manage common side effects and when to contact the clinic.</p>
 <h3>Storage and Handling</h3>
 <p>Tirzepatide must be refrigerated. At DIVA Skin Clinic Poipet, proper cold chain storage and handling protocols are followed. Do not use if the product has been improperly stored or if the appearance is abnormal.</p>

