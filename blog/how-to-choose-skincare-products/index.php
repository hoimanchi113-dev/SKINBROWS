 <h2 id="s5">5. What to Avoid</h2>
 <ul>
 <li>Market whitening creams with unlabeled ingredients — often contain steroids or mercury</li>
 <li>Products with long ingredient lists that include fragrance, alcohol, or multiple irritants</li>
 <li>Using too many active ingredients at once — layering retinol + AHA + vitamin C + niacinamide is too much</li>
 <li>Changing products too frequently — skin needs 4–6 weeks to adapt before you can judge effectiveness</li>
 <li>Physical scrubs on acne-prone or sensitive skin</li>
 </ul>

 <h2 id="s6">6. Sunscreen — The Most Important Product</h2>
 <p>At DIVA Skin Clinic Poipet, we tell every client the same thing: sunscreen is the single most important skincare product you can use. It is more important than any serum, cream, or treatment.</p>
 <p>Poipet, Cambodia has intense UV exposure year-round. Without daily sunscreen, skin treatment results fade faster, melasma returns, acne marks darken, and aging accelerates. Use SPF 50+ every day — even on cloudy days, even indoors near windows.</p>
 <p>(ID) Tabir surya adalah produk skincare paling penting. Di Poipet, paparan UV sangat intens sepanjang tahun. Gunakan SPF 50+ setiap hari — bahkan saat di dalam ruangan.</p>
 <p>(VI) Kem chống nắng là sản phẩm skincare quan trọng nhất. Tại Poipet, tia UV rất mạnh quanh năm. Dùng SPF 50+ mỗi ngày — kể cả khi ở trong nhà gần cửa sổ.</p>

