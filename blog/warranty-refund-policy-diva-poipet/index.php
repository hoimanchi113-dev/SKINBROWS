 <h2 id="s3">3. Client Rights Before Treatment</h2>
 <p>Before any branded injectable or product-based treatment at DIVA Skin Clinic Poipet, clients may request to inspect the product directly. Clients may check:</p>
 <ul>
 <li>Brand name and product name</li>
 <li>Expiry date and batch number</li>
 <li>Seal or packaging condition</li>
 <li>Supplier label or authentication mark if available</li>
 <li>Dosage or concentration as discussed during consultation</li>
 </ul>
 <p>Product verification must be requested BEFORE the session begins. Once opened and used, packaging may be disposed of per clinic hygiene protocol.</p>

 <h2 id="s4">4. Warranty Conditions</h2>
 <p>Clients may be eligible for warranty or treatment support if ALL of the following conditions are met:</p>
 <ul>
 <li>The treatment result shows no significant improvement compared to the initial assessment and agreed treatment scope</li>
 <li>A complication or unusual reaction is confirmed to be from a technical error on the clinic's side</li>
 <li>The client followed all aftercare instructions provided by DIVA Skin Clinic Poipet correctly and consistently</li>
 <li>The client did NOT use outside skincare, self-treat, or receive treatment elsewhere during recovery without informing the clinic</li>
 <li>The client contacts DIVA Skin Clinic Poipet within the warranty period — not after it has expired</li>
 <li>The client provides clear photos, treatment date, session history, and information about all products used after treatment</li>
 </ul>

 <h2 id="s5">5. Forms of Support</h2>
 <ul>
 <li>Review consultation and skin assessment</li>
 <li>Follow-up guidance related to the treatment performed at DIVA Skin Clinic Poipet</li>
 <li>Treatment plan review and adjustment</li>
 <li>Product or skincare support if appropriate</li>
 <li>Monitoring of unusual reactions related to treatment</li>
 <li>Complementary correction or additional treatment if a confirmed technical error from the clinic's side is identified</li>
 </ul>

 <h2 id="s6">6. What Is NOT Covered by Warranty</h2>
 <ul>
 <li>Dissatisfaction based on expectations that were not aligned with consultation — results that were explained as unlikely during consultation are not covered</li>
 <li>Results that vary due to individual skin response, lifestyle, sun exposure, or aftercare non-compliance</li>
 <li>Reactions caused by outside products not provided or approved by DIVA Skin Clinic Poipet</li>
 <li>Clients who visited another clinic or self-treated during the recovery period without informing DIVA</li>
 <li>Skin concerns that developed from a different cause unrelated to the treatment performed</li>
 </ul>

 <h2 id="s7">7. Refund Policy</h2>
 <p>Refunds at DIVA Skin Clinic Poipet are considered on a case-by-case basis. A refund may be considered when:</p>
 <ul>
 <li>A confirmed technical error from the clinic's side is identified after full review</li>
 <li>A paid service cannot be performed due to the client's medical condition identified at clinic</li>
 <li>A product is confirmed to be inauthenticated — refund applies to product cost only</li>
 </ul>
 <p>Refunds are NOT applicable for:</p>
 <ul>
 <li>Dissatisfaction based on unrealistic expectations not aligned with consultation</li>
 <li>Results that vary due to individual skin response, lifestyle, or aftercare non-compliance</li>
 <li>Voluntary cancellation of a prepaid treatment course without a confirmed medical reason</li>
 <li>Reactions from products used by the client outside of clinic recommendations</li>
 </ul>

 <h2 id="s8">8. How to Request Support</h2>
 <p>To request warranty consideration, treatment support, or refund review at DIVA Skin Clinic Poipet:</p>
 <ul>
 <li>Contact DIVA Skin Clinic Poipet via WhatsApp +855 93 970 584 or Telegram @diva_glow_poipet</li>
 <li>Provide your treatment date, services received, and description of the concern</li>
 <li>Submit clear photos of the concern if applicable</li>
 <li>Avoid applying new products or receiving treatment elsewhere before contacting DIVA</li>
 </ul>

