 <!-- SECTION 5 -->
 <h2 id="s5">5. Acne with Oily Skin and Clogged Pores</h2>
 <p>Oily skin does not always mean the skin is strong. Some oily skin is also dehydrated, sensitive or easily irritated. Treatment may focus on:</p>
 <ul>
 <li>Reducing clogged pores</li>
 <li>Supporting oil control</li>
 <li>Calming inflammation</li>
 <li>Improving skin texture</li>
 <li>Preventing new breakouts</li>
 </ul>

 <!-- SECTION 6 -->
 <h2 id="s6">6. Acne with Sensitive or Weak Skin Barrier</h2>
 <p>Some acne clients have already damaged their skin barrier by using too many strong products, peeling too often, over-washing, using harsh scrubs or mixing actives incorrectly. Signs of weak skin barrier include:</p>
 <ul>
 <li>Burning feeling when applying skincare</li>
 <li>Redness, dryness and tightness</li>
 <li>Peeling</li>
 <li>Itching</li>
 <li>Skin that becomes sensitive easily</li>
 </ul>

