 <h2 id="s1">1. What Is Mounjaro / Tirzepatide?</h2>
 <p>Mounjaro (tirzepatide) is an injectable medication that has gained significant attention across Southeast Asia — including among clients in Poipet, Cambodia — as a weight management support option. It was originally developed for glycemic control in type 2 diabetes, and has since been studied for its effects on body weight reduction in eligible adults.</p>
 <p>Tirzepatide works as a dual GIP and GLP-1 receptor agonist. In simpler terms, it affects two hormone pathways that regulate appetite, blood sugar, and fat metabolism. It helps reduce hunger, slow gastric emptying, and improve how the body processes glucose and fat.</p>
