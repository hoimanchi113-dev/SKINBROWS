 <h2 id="s1">1. What Is Sensitive Skin?</h2>
 <p>Sensitive skin is not always something you are born with. In many cases, sensitivity develops over time due to external factors that weaken the skin barrier. Sensitive skin reacts more easily to products, treatments, weather, and environmental triggers.</p>
 <p>(Tiếng Việt) Da nhạy cảm không phải lúc nào cũng bẩm sinh. Nhiều trường hợp da trở nên nhạy cảm do hàng rào bảo vệ da bị suy yếu bởi sản phẩm không phù hợp, lột da quá mức, tiếp xúc nắng hoặc điều trị không đúng cách.</p>
 <p>(Bahasa Indonesia) Kulit sensitif tidak selalu bawaan lahir. Banyak kasus kulit menjadi sensitif karena skin barrier melemah akibat produk yang tidak cocok, eksfoliasi berlebihan, paparan sinar matahari, atau perawatan yang tidak sesuai.</p>
 <p>Common signs of sensitive skin:</p>
 <ul>
 <li>Redness, flushing, or blotchiness — especially after applying products</li>
 <li>Burning, stinging, or tingling sensation after cleansing or using skincare</li>
 <li>Tightness and dryness even after moisturizing</li>
 <li>Easily irritated by weather, heat, or sweat</li>
 <li>Frequent breakouts or reactions to new products</li>
 <li>Skin feels uncomfortable or reactive most of the time</li>
 </ul>

 <h2 id="s2">2. Signs of a Damaged Skin Barrier</h2>
 <p>The skin barrier is the outermost layer of the skin that protects against environmental damage, water loss, and bacteria. When it is damaged, the skin becomes vulnerable, reactive, and difficult to treat.</p>
 <ul>
 <li>Persistent dryness and flakiness that doesn't improve with moisturizer</li>
 <li>Increased sensitivity to previously tolerated products</li>
 <li>Frequent redness, irritation, or visible capillaries</li>
 <li>Skin feels tight, rough, or uncomfortable throughout the day</li>
 <li>Breakouts that appear without clear reason</li>
 <li>Products that previously worked now cause stinging or reactions</li>
 </ul>
 <p>At DIVA Skin Clinic Poipet, we assess skin barrier condition as part of every consultation. If your barrier is compromised, we will adjust the treatment plan accordingly — even if you came in asking for a stronger service like CO2 laser or chemical peel.</p>

