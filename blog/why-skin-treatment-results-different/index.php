 <h2 id="s3">3. Why Before-and-After Photos Can Be Misleading</h2>
 <p>Before-and-after photos are a powerful marketing tool — but they can create unrealistic expectations. At DIVA Skin Clinic Poipet, we are careful about how we use them.</p>
 <ul>
 <li>Photos are often taken in optimal lighting for the 'after' shot and less flattering lighting for the 'before' shot.</li>
 <li>The best results are chosen to represent the treatment — not the average result.</li>
 <li>The person in the photo may have had a very specific skin condition that responded particularly well.</li>
 <li>Photos rarely show the full treatment history — how many sessions, what products, what homecare was followed.</li>
 </ul>
 <p>At DIVA Skin Clinic Poipet, we prefer to discuss realistic outcomes based on your specific skin condition — not promise results based on someone else's photo.</p>

 <h2 id="s4">4. What You Can Realistically Expect</h2>
 <h3>Acne and Oily Skin</h3>
 <p>With consistent treatment at DIVA Skin Clinic Poipet, most clients see significant reduction in active acne and oil control within 3–5 sessions. Complete acne elimination is rare because acne has hormonal and genetic components — but control and management are achievable.</p>
 <h3>Pigmentation and Melasma</h3>
 <p>Visible improvement with Pico laser and brightening treatments is typically seen after 3–6 sessions at DIVA Skin Clinic Poipet. Melasma can recur without sunscreen. Long-term management is usually needed.</p>
 <h3>Acne Scars</h3>
 <p>Meaningful improvement in scar appearance typically begins after 3–5 sessions of CO2 laser or RF microneedling at DIVA Skin Clinic Poipet. Deep ice pick scars improve more slowly than boxcar or rolling scars.</p>
 <h3>Skin Brightening</h3>
 <p>Glow and hydration improvement from skinbooster or IV drip can be visible after the first 1–3 sessions. More significant brightening requires a consistent program.</p>
 <h3>Anti-Aging and Lifting</h3>
 <p>HIFU and RF microneedling results develop gradually over 2–3 months as collagen is remodeled. One session can produce improvement, but multiple sessions produce stronger and longer-lasting results.</p>

