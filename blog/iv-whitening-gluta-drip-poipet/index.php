 <h2 id="s2">2. What's Inside a Whitening Infusion?</h2>
 <h3>Glutathione</h3>
 <p>Glutathione is the main brightening ingredient in most whitening infusions. It is a powerful antioxidant produced naturally by the body. At high concentrations, glutathione can inhibit the enzyme tyrosinase — which is involved in melanin production — potentially reducing melanin and supporting a brighter skin tone over time.</p>
 <h3>Vitamin C (Ascorbic Acid)</h3>
 <p>Vitamin C works synergistically with glutathione — it helps recycle glutathione, extends its activity, and provides additional antioxidant and brightening benefits. It also supports collagen production.</p>
 <h3>Additional Ingredients in VIP Programs</h3>
 <p>The VIP Whitening Infusion at DIVA Skin Clinic Poipet may include additional premium supportive ingredients depending on suitability: placenta extract, collagen support, advanced antioxidants, recovery formulas, and selected vitamins.</p>

