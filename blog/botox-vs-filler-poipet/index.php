 <h2 id="s2">2. What Is Filler?</h2>
 <p>Filler (dermal filler) is an injectable gel — most commonly hyaluronic acid (HA) — that adds volume, shape, or structure to selected facial areas. Unlike botox, filler does not affect muscle movement. It adds physical volume where the face has lost it or needs more definition.</p>
 <p>(Tiếng Việt) Filler là gel tiêm vào da để bổ sung thể tích, định hình hoặc tái tạo cấu trúc khuôn mặt. Tại DIVA Skin Clinic Poipet, filler được dùng để làm đầy môi, nâng mũi, định hình cằm, phục hồi thể tích má.</p>
 <p>(Bahasa Indonesia) Filler adalah gel yang disuntikkan untuk menambah volume, membentuk, atau mendukung struktur wajah. Di DIVA Skin Clinic Poipet, filler digunakan untuk bibir, hidung, dagu, pipi, dan area bawah mata.</p>
 <p>Results from filler at DIVA Skin Clinic Poipet are visible immediately and typically last 6–18 months depending on the area and product used.</p>
 <p>Common uses of Filler at DIVA Skin Clinic Poipet:</p>
 <ul>
 <li>Lip filler — add volume, improve shape, or hydrate the lips</li>
 <li>Chin enhancement — add projection and improve facial balance</li>
 <li>Nose filler — shape the nose without surgery</li>
 <li>Cheek / mid-face volume — restore or enhance cheek definition</li>
 <li>Under-eye hollow (tear trough) — fill hollow or sunken under-eye area</li>
 <li>Nasolabial folds — soften deep lines from nose to mouth corners</li>
 <li>Full face balancing — multi-area treatment for overall facial harmony</li>
 </ul>

