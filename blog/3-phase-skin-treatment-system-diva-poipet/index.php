 <h2 id="s3">3. Phase 1 — Control and Prepare</h2>
 <p>Phase 1 is about bringing the skin to a state where it can safely receive treatment and respond productively. This phase is often overlooked by clinics that want to start strong treatment immediately — but it is the foundation that determines whether treatment will work.</p>
 <h3>What Phase 1 Addresses</h3>
 <ul>
 <li>Active problems destroying skin structure — active acne, severe inflammation, barrier damage, steroid rebound</li>
 <li>Biological instability — skin reacting unpredictably, producing more pigmentation, cycling through flares</li>
 <li>Skin that cannot tolerate treatment — too sensitive, too inflamed, too compromised for laser or peel</li>
 </ul>
 <h3>Phase 1 Is Not Weakness — It Is Strategy</h3>
 <p>Some clients are frustrated when DIVA Skin Clinic Poipet recommends starting with a stabilization phase rather than immediate aggressive treatment. But the logic is clear: starting strong treatment on unstable skin produces weaker results and higher risk. Starting from a stable foundation produces stronger, faster, longer-lasting improvement.</p>

 <h2 id="s4">4. Phase 2 — Drive Change (The Main Phase)</h2>
 <p>Phase 2 is where the main work happens. The skin is now stable and ready. The target is clear. Treatment sessions are designed to create real biological change — not just surface-level improvement.</p>
 <h3>What Phase 2 Creates</h3>
 <ul>
 <li>Real structural changes — collagen remodeling, pigmentation reduction, scar improvement, skin firming</li>
 <li>Cumulative improvement — each session builds on the last, progressively driving toward the target</li>
 <li>Biological adaptation — the skin learns a new direction and maintains improvement between sessions</li>
 </ul>
 <h3>What Phase 2 Is Not</h3>
 <ul>
 <li>Not doing more treatments to make up for slow progress — more is not always better</li>
 <li>Not switching methods every session — consistency within the right direction produces better results</li>
 <li>Not skipping sessions and expecting the same outcome — consistency is the engine of Phase 2</li>
 </ul>

 <h2 id="s5">5. Phase 3 — Stabilize and Maintain Results</h2>
 <p>Phase 3 is where results are consolidated and protected. The main target has been achieved — now the goal is to make those results last.</p>
 <h3>What Phase 3 Involves</h3>
 <ul>
 <li>Lighter maintenance sessions — less intensive than Phase 2, but consistent</li>
 <li>Homecare optimization — ensuring the daily routine supports and extends treatment results</li>
 <li>Monitoring — watching for early signs of regression and adjusting before problems return</li>
 <li>Education — the client understands what to do and what to avoid to keep their results</li>
 </ul>
 <h3>Why Phase 3 Is Often Neglected</h3>
 <p>Many clients stop treatment when they see good results — assuming the improvement is permanent. But skin is dynamic. Without maintenance, the conditions that caused the original problem tend to reassert themselves over time.</p>

 <h2 id="s6">6. Why Homecare Is Not Optional</h2>
 <p>The 3-Phase system at DIVA Skin Clinic Poipet operates on two parallel tracks simultaneously: treatment at the clinic, and care at home. These two tracks cannot be separated.</p>
 <p>Clinic treatment creates the direction and drives change. Homecare maintains and extends the change between sessions. A client who receives excellent in-clinic treatment but uses the wrong products at home, skips sunscreen, or maintains lifestyle habits that trigger their condition will see significantly weaker results than a client who follows homecare guidance consistently.</p>
 <h3>Good Homecare at DIVA Poipet</h3>
 <ul>
 <li>Products matched to the current phase — recovery products in Phase 1, active ingredients in Phase 2, maintenance products in Phase 3</li>
 <li>Sunscreen every day without exception</li>
 <li>Consistency — same routine, same products, every day</li>
 <li>Communication — informing DIVA if anything changes or reacts unexpectedly</li>
 </ul>

 <h2 id="s7">7. How This System Protects You From Wrong Treatment</h2>
 <p>The 3-Phase system prevents:</p>
 <ul>
 <li>Wrong treatment at the wrong time — starting laser on inflamed skin, using peel on damaged barrier</li>
 <li>Over-treatment — too many sessions too close together without proper recovery</li>
 <li>Under-treatment — stopping too early before results are consolidated</li>
 <li>Mismatched expectations — treating with the wrong method because diagnosis was incomplete</li>
 </ul>

