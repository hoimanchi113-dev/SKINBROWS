 <!-- SECTION 11 -->
 <h2 id="s11">11. Homecare Tips During Acne Treatment</h2>
 <ul>
 <li>Use a gentle cleanser</li>
 <li>Do not scrub the skin harshly</li>
 <li>Avoid squeezing acne</li>
 <li>Avoid using too many active ingredients at the same time</li>
 <li>Avoid thick products that may clog pores</li>
 <li>Use sunscreen daily, especially if you have acne marks</li>
 <li>Follow the aftercare instructions from the clinic</li>
 </ul>

 <!-- SECTION 12 -->
 <h2 id="s12">12. Mistakes That Can Make Acne Worse</h2>

 <h3>Squeezing acne at home</h3>
 <p>This can push inflammation deeper and increase the risk of dark marks or scars.</p>

 <h3>Using too many acne products</h3>
 <p>Too many strong products can damage the skin barrier.</p>

 <h3>Stopping treatment too early</h3>
 <p>When acne improves a little, some clients stop everything. This can make acne return.</p>

 <h3>Ignoring sunscreen</h3>
 <p>Without sunscreen, acne marks may become darker and take longer to fade.</p>

