 <!-- SECTION 3 -->
 <h2 id="s3">3. Common Types of Acne</h2>

 <h3>Hidden acne / clogged pores</h3>
 <p>Hidden acne often feels like small bumps under the skin. The skin may look uneven or rough, but the acne is not always red or painful. This type of acne is often related to clogged pores, excess oil, thick skincare, heavy makeup or incomplete cleansing.</p>

 <h3>Inflamed acne</h3>
 <p>Inflamed acne appears red, swollen or painful. Some pimples may contain pus. This type needs more careful management because inflammation can increase the risk of dark marks and acne scars.</p>

 <h3>Recurring acne</h3>
 <p>Recurring acne means the acne improves for a while and then comes back again. Recurring acne usually needs a structured plan: control active acne first, then maintain the result with proper homecare and follow-up treatment.</p>

 <h3>Hormonal-looking acne</h3>
 <p>Acne around the chin, jawline or lower face may be influenced by hormones, stress, sleep, diet or lifestyle. Clinic treatment may help control the skin condition, but lifestyle and internal factors may also need attention.</p>

 <h3>Acne with sensitive skin</h3>
 <p>Some clients have acne together with redness, stinging, dryness or irritation. This means the skin barrier may be weak. For these clients, treatment needs to be gentler. Recovery and calming may be needed before stronger acne treatment.</p>

