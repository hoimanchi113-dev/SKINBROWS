 <h2 id="s5">5. The Three Phases of Skin Treatment at DIVA</h2>
 <h3>Phase 1 — Control</h3>
 <p>Address active problems. Stop active acne. Calm inflammation. Stabilize the skin. Correct any product or treatment causing irritation. Without this phase, deeper treatment may not be effective.</p>
 <h3>Phase 2 — Drive Change</h3>
 <p>Once the skin is stable, target the main concern directly. This phase uses the appropriate treatment technology or product — laser, mesotherapy, skinbooster, peel, or combination — to produce visible improvement.</p>
 <h3>Phase 3 — Stabilize and Maintain</h3>
 <p>Lock in the results. Support long-term skin health. Review homecare. Provide guidance on maintenance treatment intervals. This is where results are protected and extended over time.</p>

 <h2 id="s6">6. How to Prepare for Your First Visit</h2>
 <p>To get the most from your consultation at DIVA Skin Clinic Poipet:</p>
 <ul>
 <li>Write down your main concern — be specific about what bothers you most</li>
 <li>Note how long you have had the concern</li>
 <li>List all current skincare products you are using</li>
 <li>Mention any previous clinic treatments and results</li>
 <li>Share any allergies or medical conditions</li>
 <li>Send a skin photo on WhatsApp before your visit if possible — this helps us prepare</li>
 </ul>
 <p>You do not need to know the treatment name. Just bring your concern — DIVA Skin Clinic Poipet will guide the rest.</p>

