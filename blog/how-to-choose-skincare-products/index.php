 <h2 id="s3">3. Skincare by Skin Concern</h2>
 <h3>Acne and Oily Skin</h3>
 <ul>
 <li>Use a gentle, non-comedogenic cleanser — avoid harsh foaming cleansers that strip oil completely (this triggers more oil production)</li>
 <li>Moisturizer is still needed — choose lightweight, oil-free gel moisturizer</li>
 <li>Active ingredients: niacinamide (oil control, pore appearance), salicylic acid (use carefully and not daily), benzoyl peroxide (spot treatment only)</li>
 <li>Avoid: heavy creams, oils, comedogenic products, too many active ingredients at once</li>
 </ul>
 <h3>Pigmentation and Melasma</h3>
 <ul>
 <li>Sunscreen is non-negotiable — SPF 50 or higher, reapply every 2 hours outdoors</li>
 <li>Brightening actives: niacinamide, tranexamic acid, azelaic acid — gentler and safer than hydroquinone for long-term use</li>
 <li>Vitamin C (L-ascorbic acid) can help but can also trigger irritation on sensitive skin — start slow</li>
 <li>Avoid: Kojic acid soaps and market whitening creams with unknown ingredients</li>
 </ul>
 <h3>Sensitive and Barrier-Damaged Skin</h3>
 <ul>
 <li>Minimal routine — cleanser, moisturizer, sunscreen only</li>
 <li>Look for: ceramides, hyaluronic acid, panthenol, centella asiatica</li>
 <li>Avoid ALL strong actives: no retinol, no AHA/BHA, no vitamin C until barrier is recovered</li>
 <li>Fragrance-free products only</li>
 </ul>
 <h3>Dull Skin</h3>
 <ul>
 <li>Gentle exfoliation 1–2 times per week — enzyme exfoliant or mild AHA</li>
 <li>Hyaluronic acid serum for hydration support</li>
 <li>Niacinamide for brightness and glow</li>
 <li>Consistent sunscreen use to prevent further dullness</li>
 </ul>
 <h3>Post-Treatment Skin (After Clinic Treatment at DIVA Poipet)</h3>
 <ul>
 <li>Follow DIVA Skin Clinic Poipet aftercare instructions exactly — do not add products not approved by the clinic</li>
 <li>Focus on: gentle cleansing, thick moisturizer, sunscreen</li>
 <li>Avoid: strong actives, exfoliants, physical scrubs during recovery</li>
 <li>Contact DIVA Skin Clinic Poipet immediately if unusual reaction occurs</li>
 </ul>

