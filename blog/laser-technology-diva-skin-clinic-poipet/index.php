 <h2 id="s2">2. CO2 Fractional Laser</h2>
 <h3>How It Works</h3>
 <p>CO2 fractional laser creates thousands of tiny columns of heat in the skin. These micro-injuries stimulate the skin's natural healing process — producing new collagen, tightening existing collagen, and resurfacing the skin surface over time. The 'fractional' aspect means only a fraction of the skin is targeted per session, leaving surrounding tissue intact for faster healing.</p>
 <h3>Best For</h3>
 <ul>
 <li>Acne scars — especially boxcar and rolling scars</li>
 <li>Skin resurfacing and texture improvement</li>
 <li>Post-acne rough texture</li>
 <li>Fine lines and early aging signs</li>
 <li>Pore reduction with significant texture improvement needed</li>
 </ul>
 <h3>What to Expect</h3>
 <p>CO2 laser produces visible results but requires recovery time. After a session at DIVA Skin Clinic Poipet, skin typically appears red and slightly swollen for 5–7 days. Peeling may occur during this period. More intensive settings require longer recovery. DIVA Skin Clinic Poipet provides detailed aftercare guidance after every CO2 session.</p>
