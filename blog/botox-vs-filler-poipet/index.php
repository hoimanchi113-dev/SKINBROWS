 <h2 id="s8">8. Safety and What to Expect</h2>
 <p>At DIVA Skin Clinic Poipet, all injectable treatments use branded products from verified suppliers. Clients may request to inspect product packaging — brand name, expiry date, and batch number — before treatment begins.</p>
 <h3>After Botox:</h3>
 <ul>
 <li>Avoid rubbing or massaging the treated area for 4–6 hours</li>
 <li>Avoid lying down flat for 4 hours after injection</li>
 <li>Avoid intense exercise, heat, or alcohol for 24 hours</li>
 <li>Results appear in 3–7 days and improve over 2 weeks</li>
 </ul>
 <h3>After Filler:</h3>
 <ul>
 <li>Mild swelling and bruising is normal — especially for lip filler</li>
 <li>Avoid massage or pressure on the treated area for 48 hours</li>
 <li>Swelling usually resolves in 3–5 days for most areas</li>
 <li>Final result is visible after 2 weeks when swelling fully settles</li>
 </ul>

