 <!-- SECTION 9 -->
 <h2 id="s9">9. What Can One Acne Treatment Session Improve?</h2>
 <p>One acne treatment session may help clean the skin, reduce some clogged pores, calm mild inflammation, reduce oiliness temporarily and make the skin feel smoother. However, one session usually cannot fully control recurring acne, hormonal acne, long-term clogged pores or acne with many marks.</p>

 <!-- SECTION 10 -->
 <h2 id="s10">10. Why Acne Treatment May Need Several Sessions</h2>
 <p>Acne treatment may need several sessions because the skin changes gradually. The number of sessions depends on:</p>
 <ul>
 <li>Acne severity</li>
 <li>Skin sensitivity</li>
 <li>How long the acne has been present</li>
 <li>Whether there are acne marks or scars</li>
 <li>Homecare routine</li>
 <li>Lifestyle</li>
 <li>Hormonal factors</li>
 </ul>

