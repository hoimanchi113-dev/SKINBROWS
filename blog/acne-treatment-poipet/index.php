 <!-- SECTION 7 -->
 <h2 id="s7">7. When Should Acne Be Treated at a Clinic?</h2>
 <p>You may consider clinic treatment if:</p>
 <ul>
 <li>Acne keeps coming back</li>
 <li>Acne is inflamed, painful or swollen</li>
 <li>You have many clogged pores</li>
 <li>Acne leaves dark marks</li>
 <li>Your skin becomes rough and uneven</li>
 <li>Home treatment does not work</li>
 <li>Your skin is sensitive and reacts easily</li>
 </ul>

 <!-- SECTION 8 -->
 <h2 id="s8">8. Acne Treatment Direction at DIVA Skin Clinic Poipet</h2>
 <p>At DIVA Skin Clinic Poipet, acne treatment is planned based on your actual skin condition. We do not choose treatment only because a machine is popular or because another client had the same service.</p>

 <h3>Stage 1: Control and calm</h3>
 <p>The goal is to reduce active acne, calm inflammation, clean clogged pores and make the skin more stable. This stage is suitable when the skin has inflamed acne, clogged pores, redness or irritation.</p>

 <h3>Stage 2: Improve acne marks and texture</h3>
 <p>After acne becomes more stable, the focus can move to acne marks, rough skin, large pores, uneven tone and skin quality.</p>

 <h3>Stage 3: Maintain and prevent recurrence</h3>
 <p>Acne can return if the skin is not maintained. This stage focuses on homecare, follow-up treatment, oil control, sun protection and avoiding habits that trigger acne again.</p>

