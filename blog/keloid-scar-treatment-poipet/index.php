 <h2 id="s1">1. Understanding Keloids and Hypertrophic Scars</h2>
 <p>When skin is injured — from acne, surgery, trauma, burns, or piercing — the body produces collagen to repair the wound. In most cases this produces a flat scar that fades over time. But in some people, the body produces too much collagen — resulting in raised, thickened scar tissue.</p>
 <h3>Hypertrophic Scars</h3>
 <p>Hypertrophic scars are raised, firm, and often red or pink — but they remain within the boundaries of the original wound. They respond well to treatment at DIVA Skin Clinic Poipet.</p>
 <h3>Keloid Scars</h3>
 <p>Keloid scars grow beyond the boundaries of the original wound and can continue to expand over time. They are raised, often shiny, and may be itchy or uncomfortable. Keloids are more common in people with medium to darker skin tones — including many Vietnamese, Indonesian, Filipino, and Cambodian clients at DIVA Skin Clinic Poipet. Common locations: chest, back, shoulders, jawline, and earlobes.</p>
 <p>(ID) Keloid adalah bekas luka yang tumbuh melampaui batas luka asli dan terus membesar. Lebih umum pada tipe kulit medium hingga gelap. Lokasi umum: dada, punggung, bahu, rahang, daun telinga.</p>
 <p>(VI) Sẹo lồi (keloid) là sẹo phát triển vượt ra ngoài ranh giới vết thương và có thể tiếp tục phát triển. Phổ biến hơn ở da ngăm đến tối. Vị trí thường gặp: ngực, lưng, vai, hàm, dái tai.</p>

