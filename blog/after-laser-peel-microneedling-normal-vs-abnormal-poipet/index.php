<h2 id="s2">2. After CO2 Fractional Laser</h2>
 <h3>✅ Normal — Expected Reactions</h3>
 <ul>
 <li>Redness and warmth for 1–3 days — skin feels like a mild sunburn</li>
 <li>Mild swelling on day 1–2, especially around the eyes</li>
 <li>Tiny micro-crust or flaking from day 3–7 as skin renews</li>
 <li>Small milia (tiny white bumps) may appear temporarily — do not squeeze</li>
 <li>Skin may feel tight and dry during healing</li>
 </ul>
 <h3>⚠️ Monitor — Contact DIVA if These Occur</h3>
 <ul>
 <li>Significant redness and burning lasting beyond 5 days</li>
 <li>Skin darkening (PIH) — apply SPF strictly and contact DIVA for guidance</li>
 </ul>
 <h3>🚨 Emergency — Contact DIVA Immediately</h3>
 <ul>
 <li>Pus, discharge, or signs of infection — fever, increasing pain, spreading redness</li>
 <li>Severe blistering beyond expected peeling</li>
 </ul>
 <h3>Aftercare at Home</h3>
 <ul>
 <li>Apply B5 gel or recovery serum — do not touch or peel the skin</li>
 <li>SPF 50+ every day without exception</li>
 <li>No retinol, AHA, BHA for 7–10 days</li>
 <li>No swimming, sauna, or excessive sweating for 1 week</li>
 </ul>

 <h2 id="s3">3. After Pico Laser</h2>
 <h3>✅ Normal</h3>
 <ul>
 <li>Temporary darkening of pigmented spots 3–7 days after — the laser has targeted the pigment</li>
 <li>Mild redness for 24–48 hours</li>
 <li>Slight swelling around treated spots on day 1</li>
 </ul>
 <h3>⚠️ Monitor</h3>
 <ul>
 <li>Heavy darkening spreading beyond treated area lasting more than 7 days</li>
 </ul>
 <h3>Aftercare</h3>
 <ul>
 <li>SPF 50+ is absolutely non-negotiable after Pico laser</li>
 <li>Use tranexamic acid or vitamin C serum as directed</li>
 <li>Do not pick at darkened spots — they will clear naturally</li>
 </ul>

 <h2 id="s4">4. After Chemical Peel</h2>
 <h3>✅ Normal</h3>
 <ul>
 <li>Tingling or stinging sensation during the first few hours</li>
 <li>Light to moderate peeling from day 2–5 depending on peel strength</li>
 <li>Temporary dryness and tightness</li>
 </ul>
 <h3>🚨 Emergency</h3>
 <ul>
 <li>Blistering or significant skin lifting — contact DIVA immediately, do not apply new products</li>
 </ul>
 <h3>Aftercare</h3>
 <ul>
 <li>Moisturize generously — gentle, fragrance-free cream</li>
 <li>Do NOT peel or pull off flaking skin — let it shed naturally</li>
 <li>No physical exfoliation or scrubs</li>
 <li>SPF 50+ every day</li>
 </ul>

 <h2 id="s5">5. After RF Microneedling / PRP</h2>
 <h3>✅ Normal</h3>
 <ul>
 <li>Redness for 1–3 days — like a mild sunburn</li>
 <li>Mild tightness and swelling on day 1</li>
 <li>Small pinpoint marks from needle entry — fade within 24–48 hours</li>
 </ul>
 <h3>🚨 Emergency</h3>
 <ul>
 <li>Pus at injection points — signs of infection</li>
 <li>Severe swelling or pain after 72 hours</li>
 </ul>
 <h3>Aftercare</h3>
 <ul>
 <li>Apply B5 or HA recovery serum as directed</li>
 <li>No makeup for 24–48 hours after microneedling</li>
 <li>No retinol, AHA, strong actives for 7 days</li>
 </ul>

 <h2 id="s6">6. After HIFU</h2>
 <h3>✅ Normal</h3>
 <ul>
 <li>Tightness and mild swelling around the jaw and cheek area for 1–3 days</li>
 <li>Mild tenderness when touching the treated area</li>
 <li>Temporary slight asymmetry as swelling settles</li>
 </ul>
 <h3>🚨 Emergency</h3>
 <ul>
 <li>Facial weakness, drooping, or asymmetry lasting more than 1 week — contact DIVA immediately</li>
 </ul>
 <h3>Aftercare</h3>
 <ul>
 <li>Stay well hydrated</li>
 <li>No dental work or facial massage for 2 weeks after HIFU</li>
 </ul>

 <h2 id="s7">7. After Skinbooster / Mesotherapy</h2>
 <h3>✅ Normal</h3>
 <ul>
 <li>Small red dots at injection points — fade within 24 hours</li>
 <li>Mild swelling for 1–3 days</li>
 <li>Slightly bumpy texture as product settles — smooths within 3–5 days</li>
 </ul>
 <h3>🚨 Emergency</h3>
 <ul>
 <li>Painful, red, warm lump — signs of infection or abscess</li>
 </ul>

 <h2 id="s8">8. After Botox</h2>
 <h3>✅ Normal</h3>
 <ul>
 <li>Small red bumps at injection points — fade within a few hours</li>
 <li>Mild heaviness or pressure for 1–2 days</li>
 <li>Full effect takes 5–14 days to appear — do not judge results before then</li>
 </ul>
 <h3>🚨 Emergency</h3>
 <ul>
 <li>Eyelid drooping — contact DIVA immediately</li>
 <li>Difficulty swallowing or breathing — seek medical attention immediately</li>
 </ul>
 <h3>Aftercare</h3>
 <ul>
 <li>Do NOT massage the treated area for 24 hours</li>
 <li>Do NOT lie down for 4 hours after treatment</li>
 <li>No vigorous exercise for 24 hours</li>
 </ul>

 <h2 id="s9">9. After Filler — Including Emergency Signs</h2>
 <div class="blog-highlight" style="border-left:4px solid #991B1B;background:#FEF2F2">⚠️ CRITICAL: Vascular occlusion (blocked blood vessel) after filler is a medical emergency. Read this section carefully.</div>
 <h3>✅ Normal</h3>
 <ul>
 <li>Swelling and bruising for 2–5 days</li>
 <li>Slight asymmetry as swelling settles — evaluate at 2 weeks</li>
 </ul>
 <h3>🚨 EMERGENCY — Signs of Vascular Occlusion</h3>
 <p>Contact DIVA Skin Clinic Poipet IMMEDIATELY or seek emergency medical care if you experience:</p>
 <ul>
 <li>🚨 Sudden, intense, disproportionate pain at or near the injection site</li>
 <li>🚨 Skin turning white, pale, grey, or bluish in color</li>
 <li>🚨 Skin feeling cold or numb in the treated area</li>
 <li>🚨 Skin does not return to pink when pressed (poor capillary refill)</li>
 <li>🚨 Vision changes, blurring, or loss of vision after nose or under-eye filler</li>
 <li>🚨 Skin develops a mottled, net-like purple pattern</li>
 </ul>
 <p>Vascular occlusion means filler has blocked blood flow. This must be treated within HOURS with hyaluronidase (filler dissolving enzyme) to prevent permanent damage. Do not wait — contact DIVA Skin Clinic Poipet or emergency services immediately. WhatsApp: +855 93 970 584 | Open 12PM–3AM.</p>
 <h3>Aftercare</h3>
 <ul>
 <li>Cold compress for 24 hours — reduces swelling and bruising</li>
 <li>No vigorous exercise or alcohol for 48 hours</li>
 <li>Do not massage filler unless specifically instructed</li>
 </ul>

