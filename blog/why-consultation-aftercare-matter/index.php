 <h2 id="s2">2. What We Ask and Why</h2>
 <h3>Your Main Concern</h3>
 <p>We want to understand exactly what is bothering you — not assume based on appearance alone. A client with 'dark spots' might have melasma, PIH, sun damage, or freckles — each needs a different approach.</p>
 <h3>Your Treatment History</h3>
 <p>Previous treatments — especially laser, chemical peel, injectables, or steroid-based products — affect what we can do and when. Skin that has had recent treatment may need time to recover before new treatment begins.</p>
 <h3>Current Skincare and Products</h3>
 <p>Products you use at home affect your skin's current condition. Strong actives like retinol or AHA may need to be paused before certain treatments. Unknown whitening creams can cause reactions that complicate treatment planning.</p>
 <h3>Allergies and Medical Conditions</h3>
 <p>Certain medical conditions or medications can affect healing, skin sensitivity, or treatment suitability. DIVA Skin Clinic Poipet needs this information to plan safely.</p>
 <h3>Expected Result and Budget</h3>
 <p>We ask about your expected result so we can advise whether it is achievable — and within what timeframe and budget. Honest conversations about expectations prevent disappointment.</p>

