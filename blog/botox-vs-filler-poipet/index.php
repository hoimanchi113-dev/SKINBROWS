 <h2 id="s1">1. What Is Botox?</h2>
 <p>Botox (botulinum toxin) is a purified protein that temporarily relaxes specific muscles when injected in small, controlled amounts. At DIVA Skin Clinic Poipet, botox is used to relax overactive muscles that cause wrinkles, jaw tension, excessive sweating, or unwanted muscle bulk.</p>
 <p>(Tiếng Việt) Botox là một loại protein tinh khiết được tiêm vào cơ để tạm thời làm giãn cơ đó. Tại DIVA Skin Clinic Poipet, botox được dùng để trị nhăn, thon gọn hàm, kiểm soát đổ mồ hôi và làm nhỏ cơ bắp chân hoặc vai.</p>
 <p>(Bahasa Indonesia) Botox adalah protein murni yang disuntikkan untuk merelaksasi otot tertentu sementara. Di DIVA Skin Clinic Poipet, botox digunakan untuk perawatan kerutan, rahang V-line, keringat berlebih, dan pengecilan betis atau bahu.</p>
 <p>Results from botox at DIVA Skin Clinic Poipet typically appear within 3–7 days and last 3–6 months depending on the area and individual response.</p>
 <p>Common uses of Botox at DIVA Skin Clinic Poipet:</p>
 <ul>
 <li>Jaw slimming / V-Line — reduce jaw muscle size for a slimmer facial shape</li>
 <li>Forehead lines, frown lines, crow's feet — relax wrinkle-causing muscles</li>
 <li>Brow lift — lift the tail of the eyebrow for a more refreshed look</li>
 <li>Underarm and palm sweating control — reduce excessive sweating</li>
 <li>Shoulder slimming (Traptox) — relax the trapezius muscle</li>
 <li>Calf and arm slimming — reduce muscle bulk in selected areas</li>
 <li>Neck lines / Barbie Neck — soften neck bands and horizontal lines</li>
 </ul>

