 <h2 id="s4">4. Acne with Acne Marks and Dark Spots</h2>
 <p>Many clients do not only have acne. They also have acne marks that may appear as:</p>
 <ul>
 <li>Red marks after pimples</li>
 <li>Brown marks after inflammation</li>
 <li>Uneven skin tone</li>
 <li>Dark spots after squeezing acne</li>
 <li>Rough texture after repeated acne</li>
 </ul>
 <p>At DIVA Skin Clinic Poipet, acne and acne marks may be treated in stages. First, we control active acne and inflammation. Then we improve marks, skin tone and texture.</p>

