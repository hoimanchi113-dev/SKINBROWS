 <h2 id="s2">2. Types of Pigmentation</h2>
 <h3>Epidermal Melasma</h3>
 <p>Found in the upper layers of the skin. Appears as well-defined brown patches. Responds better to treatment — Pico laser, chemical peel, and brightening mesotherapy at DIVA Skin Clinic Poipet can produce visible improvement.</p>
 <h3>Dermal Melasma</h3>
 <p>Deeper in the skin layers. Appears as grey-brown patches with less defined edges. Harder to treat. Results are slower and require more patience and consistent sessions.</p>
 <h3>Mixed Melasma</h3>
 <p>A combination of epidermal and dermal melasma. Most clients at DIVA Skin Clinic Poipet have mixed melasma. A combination of treatments is usually needed.</p>
 <h3>Post-Inflammatory Hyperpigmentation (PIH)</h3>
 <p>Dark marks that appear after acne, irritation, or injury. Very common in Vietnamese, Indonesian, Filipino, and Cambodian skin types. Responds well to brightening treatments when approached correctly.</p>
 <h3>Sun Spots / Age Spots</h3>
 <p>Flat, well-defined dark spots from long-term sun exposure. More common on the face, hands, and upper chest. Respond well to Pico laser at DIVA Skin Clinic Poipet.</p>

