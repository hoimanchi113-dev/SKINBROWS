 <h2 id="s2">2. Who Is This Treatment For?</h2>
 <p>Medical weight management with injectable support at DIVA Skin Clinic Poipet may be considered for clients who:</p>
 <ul>
 <li>Have a BMI that indicates overweight or obesity and have not achieved results through diet and exercise alone</li>
 <li>Have obesity-related health concerns such as type 2 diabetes or metabolic syndrome</li>
 <li>Want a medically supervised approach to weight loss rather than unsupervised products</li>
 <li>Are not pregnant, not breastfeeding, and have no contraindicated medical conditions</li>
 <li>Understand that this is a prescription medicine requiring ongoing monitoring</li>
 </ul>
 <p>This treatment is NOT appropriate for:</p>
 <ul>
 <li>Clients with personal or family history of medullary thyroid carcinoma or MEN2 syndrome</li>
 <li>Clients with severe pancreatitis history</li>
 <li>Pregnant or breastfeeding clients</li>
 <li>Clients on certain medications — a full medication review is required</li>
 <li>Clients who want fast, effortless results without lifestyle changes — this medication supports lifestyle improvement, not replaces it</li>
 </ul>

