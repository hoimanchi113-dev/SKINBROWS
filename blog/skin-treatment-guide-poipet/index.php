 <h2 id="s2">2. Understanding Your Main Skin Concern</h2>
 <p>Start by identifying your main concern. At DIVA Skin Clinic Poipet, skin concerns are grouped into these categories:</p>
 <h3>Acne and Oily Skin</h3>
 <p>Active pimples, whiteheads, blackheads, congestion, clogged pores, recurring breakouts. Oily skin that always looks shiny. This needs acne control as the first priority — before any resurfacing or aesthetic treatment.</p>
 <h3>Pigmentation and Dark Spots</h3>
 <p>Brown patches, freckles, melasma, post-acne dark marks, sun spots, uneven skin tone. These respond to Pico laser, brightening peel, and brightening meso at DIVA Skin Clinic Poipet.</p>
 <h3>Acne Scars and Texture</h3>
 <p>Pitted scars, rough skin surface, rolling depressions, boxcar scars, textured skin. These need collagen remodeling — CO2 laser and RF microneedling at DIVA Skin Clinic Poipet.</p>
 <h3>Pores and Oily Texture</h3>
 <p>Visibly enlarged pores, rough texture, congestion. Combination of oil control, peel, RF microneedling.</p>
 <h3>Dull Skin</h3>
 <p>Lack of glow, tired-looking skin, uneven tone without defined pigmentation. Responds well to brightening meso, glow peel, skinbooster at DIVA Skin Clinic Poipet.</p>
 <h3>Sensitive and Damaged Skin</h3>
 <p>Redness, burning, irritation, tight skin, reactive skin. Needs barrier recovery first — not strong treatment.</p>
 <h3>Aging and Lifting</h3>
 <p>Fine lines, wrinkles, skin laxity, early sagging. HIFU, RF microneedling, Profhilo, botox at DIVA Skin Clinic Poipet.</p>

